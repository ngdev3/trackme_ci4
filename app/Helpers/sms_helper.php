if (! function_exists('msg91_debug_log')) {
    function msg91_debug_log($result)
    {
        $log_dir = WRITEPATH . 'logs';
        if (! is_dir($log_dir) || ! is_writable($log_dir)) {
            return false;
        }

        $safe_result = $result;
        if (isset($safe_result['payload']['recipients'])) {
            foreach ($safe_result['payload']['recipients'] as $key => $recipient) {
                if (isset($recipient['mobiles'])) {
                    $mobile = (string) $recipient['mobiles'];
                    $safe_result['payload']['recipients'][$key]['mobiles'] = strlen($mobile) > 4
                        ? str_repeat('*', strlen($mobile) - 4) . substr($mobile, -4)
                        : '****';
                }
            }
        }

        $line = '[' . date('Y-m-d H:i:s') . '] ' . json_encode($safe_result) . PHP_EOL;
        return (bool) file_put_contents($log_dir . '/msg91_sms_debug-' . date('Y-m-d') . '.log', $line, FILE_APPEND);
    }
}

if (! function_exists('msg91_send_template')) {
    function msg91_send_template($mobile, $template_type, $message_data = [], $options = [])
    {
        $template = msg91_sms_templates($template_type);
        if (! $template) {
            return ['status' => false, 'message' => 'Invalid MSG91 template type: ' . $template_type];
        }

        $recipient = array_merge(
            ['mobiles' => msg91_normalize_mobile($mobile)],
            msg91_template_vars($template_type, $message_data)
        );

        $payload = [
            'template_id' => $template['template_id'],
            'short_url' => isset($options['short_url']) ? (string) $options['short_url'] : '0',
            'recipients' => [$recipient],
        ];
        if (isset($options['realTimeResponse'])) {
            $payload['realTimeResponse'] = (string) $options['realTimeResponse'];
        }

        $curl = curl_init();
        $curl_options = [
            CURLOPT_URL => MSG91_FLOW_URL,
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_ENCODING => '',
            CURLOPT_MAXREDIRS => 10,
            CURLOPT_TIMEOUT => 30,
            CURLOPT_HTTP_VERSION => CURL_HTTP_VERSION_1_1,
            CURLOPT_CUSTOMREQUEST => 'POST',
            CURLOPT_POSTFIELDS => json_encode($payload),
            CURLOPT_HTTPHEADER => [
                'accept: application/json',
                'authkey: ' . MSG91_AUTH_KEY,
                'content-type: application/json',
            ],
        ];

        $ca_bundle = msg91_ca_bundle_path();
        if ($ca_bundle) {
            $curl_options[CURLOPT_CAINFO] = $ca_bundle;
        }

        curl_setopt_array($curl, $curl_options);
        $response = curl_exec($curl);
        $error = curl_error($curl);
        $http_code = curl_getinfo($curl, CURLINFO_HTTP_CODE);
        curl_close($curl);

        if ($error) {
            return ['status' => false, 'message' => 'cURL Error: ' . $error, 'payload' => $payload];
        }

        $decoded_response = json_decode($response, true);
        $response_data = $decoded_response ?: $response;
        $response_type = is_array($decoded_response) && isset($decoded_response['type']) ? strtolower($decoded_response['type']) : '';
        $is_success = ($http_code >= 200 && $http_code < 300 && $response_type !== 'error');

        $result = [
            'status' => $is_success,
            'http_code' => $http_code,
            'message' => is_array($decoded_response) && isset($decoded_response['message']) ? $decoded_response['message'] : null,
            'response' => $response_data,
            'payload' => $payload,
        ];

        msg91_debug_log($result);
        return $result;
    }
