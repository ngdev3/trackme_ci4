if (! function_exists('msg91_normalize_mobile')) {
    function msg91_normalize_mobile($mobile, $country_code = '91')
    {
        $mobile = preg_replace('/\D+/', '', (string) $mobile);
        $mobile = ltrim($mobile, '0');

        if (strpos($mobile, $country_code) !== 0) {
            return $country_code . $mobile;
        }

        return $mobile;
    }
}

if (! function_exists('msg91_template_vars')) {
    function msg91_template_vars($template_type, $message_data = [])
    {
        $template = msg91_sms_templates($template_type);
        if (! $template) {
            return [];
        }
        if (! is_array($message_data)) {
            $message_data = [$message_data];
        }

        $vars = [];
        foreach ($template['variables'] as $index => $name) {
            $position = $index + 1;
            $value = '';

            if (array_key_exists($name, $message_data)) {
                $value = $message_data[$name];
            } elseif (array_key_exists('var' . $position, $message_data)) {
                $value = $message_data['var' . $position];
            } elseif (array_key_exists($index, $message_data)) {
                $value = $message_data[$index];
            } elseif (array_key_exists($position, $message_data)) {
                $value = $message_data[$position];
            }

            $value = (string) $value;
            $vars['var' . $position] = $value;
            $vars['VAR' . $position] = $value;
        }

        return $vars;
    }
}

